import esbuild from 'esbuild';
import process from 'process';
import fs from 'node:fs';
import path from 'node:path';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// 读取根目录 .env.local（不入库）中的 PRESSROOM_VAULT；配置后构建产物复制到该 vault 的插件目录
function readVaultPath() {
	if (!fs.existsSync('.env.local')) return undefined;
	const line = fs
		.readFileSync('.env.local', 'utf-8')
		.split(/\r?\n/)
		.find((l) => l.startsWith('PRESSROOM_VAULT='));
	const value = line?.slice('PRESSROOM_VAULT='.length).trim();
	return value || undefined;
}

const vault = readVaultPath();
const pluginDir = vault ? path.join(vault, '.obsidian', 'plugins', 'pressroom') : undefined;
if (vault && !fs.existsSync(vault)) {
	throw new Error(`PRESSROOM_VAULT 指向的目录不存在：${vault}`);
}

const copyToVault = {
	name: 'copy-to-vault',
	setup(build) {
		build.onEnd((result) => {
			if (!pluginDir || result.errors.length > 0) return;
			fs.mkdirSync(pluginDir, { recursive: true });
			for (const file of ['main.js', 'manifest.json', 'styles.css']) {
				fs.copyFileSync(file, path.join(pluginDir, file));
			}
			console.log(`已复制到 ${pluginDir}`);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [copyToVault],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
